def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()

def extract_member(path, signature):
    """Вырезать метод/свойство вместе с телом по началу сигнатуры (сопоставление скобок)."""
    src = read(path)
    i = src.index(signature)
    # вернуться к началу строки с комментарием-доком, если он есть
    start = src.rfind("\n\n", 0, i)
    start = start + 2 if start != -1 else i
    # тело может быть выражением: public void M(...) => ...;
    brace = src.find("{", i)
    arrow = src.find("=>", i)
    semi = src.find(";", i)
    if arrow != -1 and arrow < semi and (brace == -1 or arrow < brace):
        return dedent_lines(src[start:semi + 1])

    # иначе — обычное тело в фигурных скобках
    j = src.index("{", i)
    depth = 0
    k = j
    while True:
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    body = src[start:k + 1]
    return dedent_lines(body)

def dedent_lines(text):
    lines = text.rstrip().splitlines()
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines)


def extract_case(path, signature, case_label):
    """Вырезать ветку switch (case ...: { ... }) внутри указанного метода."""
    src = read(path)
    i = src.index(signature)
    j = src.index(case_label, i)
    k = src.index("{", j)
    depth = 0
    m = k
    while True:
        if src[m] == "{":
            depth += 1
        elif src[m] == "}":
            depth -= 1
            if depth == 0:
                break
        m += 1
    return dedent_lines(src[j:m + 1])

